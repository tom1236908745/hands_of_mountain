"""ep04『塞翁が馬』の音楽：昼の明るい曲 → 風・ころぶ音 → 夜の流れ星 → あたたかい結び。"""
from audio import Mix

DURATION = 35.5


def build() -> Mix:
    m = Mix(DURATION, seed=4)
    m.birds(0, 14, vel=0.04)
    m.wind(vel=0.03)
    m.crickets(vel=0.03, t0=20, t1=35)
    m.chords([(0, 4, ["C3", "G3", "E4"]), (4, 7.6, ["A2", "E3", "C4"]), (7.6, 10, ["F3", "C4", "A4"]),
              (10, 13.5, ["C3", "G3", "E4"]), (13.5, 15.4, ["G3", "D4", "B4"]), (15.4, 19.5, ["A2", "E3", "C4"]),
              (19.5, 21.5, ["F3", "C4", "A4"]), (21.5, 25.5, ["C3", "G3", "E4", "D5"]),
              (25.5, 30, ["F3", "A3", "C4", "E4"]), (30, 34.5, ["C3", "G3", "C4", "E4"])], vel=0.5)
    m.melody([("E5", 1), ("G5", 1), ("A5", 1), ("G5", 1), ("E5", 2), ("D5", 2)], 0.5, 0.38)
    m.gust(3.6, dur=3.2, vel=0.22)
    m.notes([(5.0, "A4"), (5.7, "G4"), (6.4, "E4")], vel=0.4)                  # しょんぼり
    m.melody([("C5", 1), ("E5", 1), ("G5", 2), ("A5", 1), ("G5", 1), ("C6", 3)], 10.0, 0.36, vel=0.5)
    m.notes([(13.6, "G5"), (14.2, "B5"), (14.8, "D6")], vel=0.35, decay=0.8)  # ぴょん
    m.boing(15.9)
    m.notes([(16.5, "E5"), (17.4, "C5"), (18.3, "A4")], vel=0.35)
    for i, t in enumerate([21.0, 21.6, 22.1, 22.7, 23.2, 23.8, 24.3]):       # 流れ星
        m.arpeggio(["E6", "G6", "C7"], t, 0.05, vel=0.22, decay=1.2)
    m.melody([("E5", 1), ("G5", 1), ("A5", 2), ("G5", 1), ("E5", 1), ("D5", 1), ("C5", 3)], 25.8, 0.48, vel=0.5,
             decay=2.2)
    for t, n in ((30.4, "G5"), (31.4, "E5"), (32.4, "D5"), (33.4, "C5")):
        m.music_box(n, t, vel=0.35, decay=2.4)
    return m
