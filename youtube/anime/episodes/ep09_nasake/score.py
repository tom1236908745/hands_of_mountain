"""ep09『情けは人の為ならず』の音楽：雨（静か）→ 傘をわたす（あたたかい）→ ひとりで ずぶぬれ（短調）→ 戻ってくる（明るく）→ 虹。"""
from audio import Mix

DURATION = 35.0


def build() -> Mix:
    m = Mix(DURATION, seed=9)
    m.rain(0.0, 24.0, vel=0.07)
    m.birds(24.0, 34, vel=0.035)
    m.chords([(0, 3.8, ["A2", "E3", "C4"]), (3.8, 7.0, ["F3", "C4", "A4"]), (7.0, 10.0, ["C3", "G3", "E4"]),
              (10.0, 15.2, ["D3", "A3", "F4"]), (15.2, 18.4, ["G3", "D4", "B4"]), (18.4, 21.4, ["C3", "G3", "E4", "D5"]),
              (21.4, 25.6, ["F3", "C4", "A4", "E5"]), (25.6, 30.0, ["F3", "A3", "C4", "E4"]),
              (30.0, 34.5, ["C3", "G3", "C4", "E4"])], vel=0.5)
    m.notes([(0.8, "E5"), (2.0, "C5"), (3.0, "A4")], vel=0.35, decay=2.2)
    m.melody([("F5", 1), ("A5", 1), ("C6", 2), ("A5", 1), ("G5", 2)], 4.0, 0.4, vel=0.45)      # 傘をわたす
    m.notes([(10.4, "A4"), (11.4, "F4"), (13.6, "D4")], vel=0.35, decay=2.4)                 # ずぶぬれ
    m.pop(12.95, vel=0.2, note="G5")                                                           # くしゅん
    m.notes([(15.4, "G4"), (16.0, "B4"), (16.6, "D5"), (17.2, "G5")], vel=0.4)                # 戻ってくる
    m.arpeggio(["C5", "E5", "G5", "C6", "E6"], 19.4, 0.1, vel=0.4, decay=1.6)
    m.melody([("E5", 1), ("G5", 1), ("A5", 2), ("G5", 1), ("E5", 1), ("G5", 1), ("C6", 3)], 20.0, 0.42, vel=0.5)
    m.arpeggio(["C5", "E5", "G5", "C6", "E6", "G6"], 23.4, 0.1, vel=0.35, decay=1.8)          # 虹
    m.melody([("E5", 1), ("D5", 1), ("C5", 2), ("D5", 1), ("E5", 1), ("C5", 3)], 25.9, 0.5, vel=0.45, decay=2.2)
    for t, n in ((30.2, "G5"), (31.2, "E5"), (32.2, "D5"), (33.2, "C5")):
        m.music_box(n, t, vel=0.35, decay=2.4)
    return m
