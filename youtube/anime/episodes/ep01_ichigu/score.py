"""『一隅を照らす』の音楽・効果音（spec.md「音楽・効果音」に対応）。"""
from audio import Mix

DURATION = 38.0


def build() -> Mix:
    m = Mix(DURATION)

    # 環境音：虫の声・夜風（全編小さく）
    m.crickets(vel=0.035)
    m.wind(vel=0.05)

    # ---- 起 0–6.5：ハ長調ペンタトニックの穏やかな旋律
    m.pad(["C3", "G3", "E4"], 0.0, 3.3, vel=0.6, attack=1.5)
    m.pad(["A2", "E3", "C4"], 3.3, 6.5, vel=0.55)
    m.melody([("E5", 1), ("G5", 1), ("A5", 2), ("G5", 1), ("E5", 1), ("D5", 2),
              ("C5", 1), ("D5", 1), ("E5", 1), ("G5", 1), ("E5", 2), ("D5", 2)], 0.6, 0.36, vel=0.55)

    # ---- 承 6.5–12.5：イ短調・音数少なく。光が消える瞬間に「ピッ」
    m.pad(["A2", "E3", "C4"], 6.5, 9.5, vel=0.45)
    m.pad(["D3", "A3", "F4"], 9.5, 12.5, vel=0.4)
    for t, n in ((6.9, "E5"), (7.8, "C5"), (9.3, "A4"), (10.2, "B4"), (11.5, "A4"), (12.0, "E4")):
        m.music_box(n, t, vel=0.42, decay=2.0)
    for t in (8.72, 10.92):
        m.blip_down(t)

    # ---- 転 12.5–19.8：F → G と上がっていく、期待感のある進行
    m.pad(["F3", "C4", "A4"], 12.5, 16.4, vel=0.5)
    m.pad(["G3", "D4", "B4"], 16.4, 19.8, vel=0.65, attack=2.0)
    for t, n, v in ((12.9, "A4", 0.4), (13.7, "C5", 0.42), (14.6, "F5", 0.55), (15.5, "E5", 0.45),
                    (16.5, "D5", 0.45), (17.2, "G5", 0.5), (18.0, "B4", 0.35), (18.0, "D5", 0.35),
                    (18.8, "G5", 0.45), (19.2, "A5", 0.5), (19.5, "B5", 0.55)):
        m.music_box(n, t, vel=v)

    # ---- 灯る 19.8–24.4：駆け上がるアルペジオ＋暖かい和音のふくらみ
    m.shimmer(19.6, dur=1.8, vel=0.18)
    m.arpeggio(["C5", "E5", "G5", "C6", "E6", "G6", "C7"], 19.8, 0.06, vel=0.55, decay=1.6)
    m.pad(["C3", "G3", "C4", "E4", "G4", "D5"], 19.8, 24.4, vel=0.85, attack=0.6)
    m.arpeggio(["G5", "C6", "E6", "G6"], 21.4, 0.12, vel=0.35, decay=1.4)
    m.melody([("E5", 1), ("G5", 1), ("C6", 3)], 22.3, 0.4, vel=0.45)

    # ---- 結 24.4–33.6：旋律が解決し、ハ長調で締める
    m.pad(["F3", "A3", "C4", "A4"], 24.4, 26.7, vel=0.6)
    m.pad(["G3", "B3", "D4", "G4"], 26.7, 29.0, vel=0.6)
    m.pad(["C3", "G3", "C4", "E4", "G4"], 29.0, 33.8, vel=0.75, attack=1.0)
    m.melody([("E5", 1), ("G5", 1), ("A5", 2), ("G5", 1), ("E5", 1), ("D5", 2),
              ("E5", 1), ("D5", 1), ("C5", 4)], 24.6, 0.45, vel=0.55, decay=2.2)
    m.arpeggio(["C6", "E6", "G6"], 29.6, 0.14, vel=0.3, decay=2.2)

    # ---- 余韻 34–38：静かなコーダ → フェードアウト
    m.pad(["C3", "G3", "E4"], 33.6, 37.2, vel=0.45, release=1.5)
    for t, n in ((34.0, "G5"), (34.8, "E5"), (35.6, "D5"), (36.4, "C5")):
        m.music_box(n, t, vel=0.38, decay=2.4)
    return m
