"""ep05『目から鱗』の音楽：のどかな昼 → こわい黒ねこ（低い音）→ 雨（短調）→ 傘（あたたかい和音）→ うろこ（キラリ）→ 虹。"""
from audio import Mix

DURATION = 36.0


def build() -> Mix:
    m = Mix(DURATION, seed=5)
    m.birds(0, 8, vel=0.04)
    m.birds(25.5, 35, vel=0.035)
    m.wind(vel=0.025)
    m.rain(9.0, 25.5, vel=0.07)
    m.chords([(0, 4, ["C3", "G3", "E4"]), (4, 8.4, ["A2", "E3", "C4"]), (8.4, 14, ["D3", "A3", "F4"]),
              (14, 17, ["A2", "E3", "C4"]), (17, 20.5, ["F3", "C4", "A4"]), (20.5, 22.6, ["G3", "D4", "B4"]),
              (22.6, 27, ["C3", "G3", "E4", "D5"]), (27, 31.4, ["F3", "A3", "C4", "E4"]),
              (31.4, 35.5, ["C3", "G3", "C4", "E4"])], vel=0.5)
    m.melody([("G5", 1), ("E5", 1), ("G5", 1), ("A5", 1), ("G5", 2), ("E5", 2)], 0.4, 0.4, vel=0.45)
    m.notes([(4.4, "E3"), (5.0, "D#3"), (5.6, "E3")], vel=0.5, decay=1.2)        # くろ（ちょっとこわい）
    m.notes([(9.6, "A4"), (10.8, "C5"), (12.0, "E5"), (13.2, "D5")], vel=0.35, decay=2.2)
    m.notes([(17.4, "F4"), (17.9, "A4"), (18.4, "C5"), (19.0, "F5")], vel=0.4)   # 傘
    m.arpeggio(["E6", "G6", "B6", "E7"], 20.75, 0.09, vel=0.3, decay=1.0)        # ポロリ
    m.arpeggio(["G6", "C7"], 21.3, 0.12, vel=0.25, decay=1.0)
    m.melody([("E5", 1), ("G5", 1), ("C6", 2), ("B5", 1), ("G5", 1), ("A5", 2)], 22.8, 0.4, vel=0.5)
    m.arpeggio(["C5", "E5", "G5", "C6", "E6"], 25.4, 0.1, vel=0.35, decay=1.8)   # 虹
    m.melody([("E5", 1), ("D5", 1), ("C5", 2), ("D5", 1), ("E5", 1), ("C5", 3)], 27.3, 0.5, vel=0.45, decay=2.2)
    for t, n in ((31.6, "G5"), (32.6, "E5"), (33.6, "C5")):
        m.music_box(n, t, vel=0.35, decay=2.4)
    return m
