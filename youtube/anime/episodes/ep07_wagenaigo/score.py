"""ep07『和顔愛語』の音楽：くもった朝（音少なめ）→ にっこりのたびに音が増え、明るくなっていく。"""
from audio import Mix

DURATION = 36.0


def build() -> Mix:
    m = Mix(DURATION, seed=7)
    m.wind(vel=0.025)
    m.birds(6.5, 35, vel=0.03)
    m.chords([(0, 4.5, ["D3", "A3", "F4"]), (4.5, 6.2, ["A2", "E3", "C4"]), (6.2, 9.0, ["C3", "G3", "E4"]),
              (9.0, 12.6, ["F3", "C4", "A4"]), (12.6, 14.2, ["G3", "D4", "B4"]), (14.2, 17.8, ["C3", "G3", "E4", "D5"]),
              (17.8, 20.6, ["A2", "E3", "C4"]), (20.6, 22.8, ["F3", "C4", "A4", "E5"]),
              (22.8, 26.8, ["C3", "G3", "C4", "E4", "G4"]), (26.8, 31.2, ["F3", "A3", "C4", "E4"]),
              (31.2, 35.5, ["C3", "G3", "C4", "E4"])], vel=0.5)
    m.notes([(0.8, "A4"), (2.2, "F4"), (3.6, "E4")], vel=0.3, decay=2.2)          # くもった朝
    for t0, notes in ((6.2, ["C5", "E5", "G5"]), (9.0, ["F5", "A5", "C6"]), (14.2, ["G5", "B5", "D6"]),
                      (20.6, ["C6", "E6", "G6", "C7"])):                           # にっこり！
        m.arpeggio(notes, t0, 0.08, vel=0.4, decay=1.4)
    for t0 in (6.5, 12.6, 17.9):                                                  # ハートが飛ぶ
        m.notes([(t0, "E6"), (t0 + 0.3, "G6"), (t0 + 0.6, "C7")], vel=0.2, decay=0.8)
    import random
    r = random.Random(3)
    for t in [6.4, 6.7, 9.1, 9.5, 14.3, 14.6, 20.7, 21.0] + [22.8 + r.uniform(0, 1.8) for _ in range(10)]:
        m.pop(t, vel=0.12, note=r.choice(["C6", "D6", "E6", "G6", "A6"]))          # 花が咲く
    m.melody([("C5", 1), ("E5", 1), ("G5", 1), ("A5", 1), ("G5", 2), ("E5", 1), ("G5", 1), ("C6", 3)], 22.9, 0.4,
             vel=0.5)
    m.melody([("E5", 1), ("G5", 1), ("A5", 2), ("G5", 1), ("E5", 1), ("D5", 1), ("C5", 3)], 27.1, 0.48, vel=0.45,
             decay=2.2)
    for t, n in ((31.4, "G5"), (32.4, "E5"), (33.4, "D5"), (34.4, "C5")):
        m.music_box(n, t, vel=0.35, decay=2.4)
    return m
